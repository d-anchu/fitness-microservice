// ============================================================
// ActivityDetail.jsx
// Purpose: Fetches the AI-generated recommendation for a single
// activity (identified by the :id URL parameter) and displays
// the analysis text, suggestion list, and safety tips.
// ============================================================

// React hooks:
//   useEffect – triggers the API call when the component mounts
//   useState  – stores recommendation data, loading, and error state
import { useEffect, useState } from 'react'

// Routing hooks:
//   useParams   – reads dynamic segments from the URL (e.g. :id)
//   useNavigate – lets us go back to the activity list
import { useParams, useNavigate } from 'react-router-dom'

// Material-UI components used in this file:
import {
  Alert,            // Displays error / warning messages
  Box,              // Generic layout wrapper
  Button,           // "Back" navigation button
  Card,             // Section cards (analysis, suggestions, safety)
  CardContent,      // Padded inner area of a card
  Chip,             // Badge-style pill for safety tips
  CircularProgress, // Spinning loading indicator
  List,             // Ordered/unordered list container
  ListItem,         // Individual item in a list
  ListItemText,     // Renders primary and secondary text in a ListItem
  Typography,       // Styled text components
} from '@mui/material'

// ArrowBackIcon – the left-pointing arrow displayed on the Back button
import ArrowBackIcon from '@mui/icons-material/ArrowBack'

// getActivityDetail – calls GET /api/recommendations/activity/{id}
// The axios interceptor adds the Authorization header automatically.
import { getActivityDetail } from '../services/api'

const ActivityDetail = () => {
  // ----------------------------------------------------------
  // ROUTE PARAMETER
  // useParams reads the :id segment from the current URL.
  // For the route /activities/abc123, id === 'abc123'.
  // ----------------------------------------------------------
  const { id } = useParams()

  // navigate function used by the Back button to return to /activities
  const navigate = useNavigate()

  // ----------------------------------------------------------
  // STATE MANAGEMENT
  // ----------------------------------------------------------

  // recommendation: the recommendation object returned by the AI service.
  // Shape: { activityType, recommendation, suggestions[], safety[] }
  const [recommendation, setRecommendation] = useState(null)

  // loading: true while the API request is in-flight
  const [loading, setLoading] = useState(true)

  // error: error message string if fetch fails, null on success
  const [error, setError] = useState(null)

  // ----------------------------------------------------------
  // FETCH RECOMMENDATION ON MOUNT
  // Depends on [id] so it re-runs if the user navigates between
  // different activity detail pages without unmounting the component.
  // ----------------------------------------------------------
  useEffect(() => {
    const fetchRecommendation = async () => {
      try {
        setLoading(true)

        // API call: GET /api/recommendations/activity/{id}
        // Returns the AI recommendation that was generated by the
        // AI service when the activity was originally submitted.
        const response = await getActivityDetail(id)

        // Store the recommendation object from the response body
        setRecommendation(response.data)
        setError(null) // Clear any previous error
      } catch (err) {
        console.error('Failed to fetch recommendation:', err)

        if (err.response?.status === 404) {
          // 404 means the recommendation hasn't been generated yet.
          // The AI service processes activities asynchronously via RabbitMQ,
          // so there can be a brief delay after an activity is submitted.
          setError('Recommendation not yet available. The AI is still processing your activity. Try again in a moment.')
        } else {
          // Any other error (500, 401, network failure, etc.)
          setError(err.response?.data?.message || 'Failed to load recommendation.')
        }
      } finally {
        setLoading(false)
      }
    }

    // Only make the API call if we actually have an id from the URL
    if (id) {
      fetchRecommendation()
    }
  }, [id]) // Re-run whenever the activity id in the URL changes

  // ----------------------------------------------------------
  // RENDER: LOADING STATE
  // ----------------------------------------------------------
  if (loading) {
    return (
      <Box sx={{display: 'flex', justifyContent: 'center', p: 4}}>
        <CircularProgress />
      </Box>
    )
  }

  // ----------------------------------------------------------
  // RENDER: MAIN CONTENT
  // The Back button is always shown.
  // The Alert appears when there is an error.
  // The recommendation cards appear only when data was fetched.
  // ----------------------------------------------------------
  return (
    <Box sx={{p: 2}}>
      {/* Back button: navigates to the activity list */}
      <Button
        startIcon={<ArrowBackIcon />}
        onClick={() => navigate('/activities')}
        sx={{mb: 2}}
      >
        Back to Activities
      </Button>

      {/* Error / warning banner */}
      {error && (
        <Alert severity="warning" sx={{mb: 2}}>
          {error}
        </Alert>
      )}

      {/* Recommendation content – only rendered when the fetch succeeded */}
      {recommendation && (
        <>
          {/* Page heading – shows which activity type this recommendation is for */}
          <Typography variant="h4" gutterBottom>
            {recommendation.activityType} Recommendation
          </Typography>

          {/* --------------------------------------------------------
              OVERALL ANALYSIS CARD
              Displays the main AI-generated narrative analysis text.
          -------------------------------------------------------- */}
          <Card sx={{mb: 2}}>
            <CardContent>
              <Typography variant="h6" gutterBottom>
                Overall Analysis
              </Typography>
              {/*
                recommendation.recommendation is the main text paragraph
                produced by the AI service describing performance and advice.
              */}
              <Typography variant="body1" paragraph>
                {recommendation.recommendation}
              </Typography>
            </CardContent>
          </Card>

          {/* --------------------------------------------------------
              RECOMMENDATIONS LIST CARD
              Shows actionable bullet-point suggestions from the AI.
              Only rendered when the suggestions array is non-empty.
          -------------------------------------------------------- */}
          {recommendation.suggestions && recommendation.suggestions.length > 0 && (
            <Card sx={{mb: 2}}>
              <CardContent>
                <Typography variant="h6" gutterBottom>
                  Recommendations
                </Typography>
                {/*
                  List component renders suggestions as an HTML list.
                  Each suggestion is a string in the array; index is used
                  as the React key because suggestions have no unique id.
                */}
                <List>
                  {recommendation.suggestions.map((suggestion, index) => (
                    <ListItem key={index}>
                      <ListItemText
                        primary={suggestion}
                        primaryTypographyProps={{variant: 'body2'}}
                      />
                    </ListItem>
                  ))}
                </List>
              </CardContent>
            </Card>
          )}

          {/* --------------------------------------------------------
              SAFETY TIPS CARD
              Displays safety warnings as red outlined Chip badges.
              Only rendered when the safety array is non-empty.
          -------------------------------------------------------- */}
          {recommendation.safety && recommendation.safety.length > 0 && (
            <Card>
              <CardContent>
                <Typography variant="h6" gutterBottom>
                  Safety Tips
                </Typography>
                {/*
                  Each safety tip is wrapped in a Chip:
                  - color="error" gives it a red tint (appropriate for warnings)
                  - variant="outlined" uses the bordered pill style
                  Box with display:flex and flexWrap:wrap arranges chips
                  in a responsive row that wraps to the next line.
                */}
                <Box sx={{display: 'flex', flexWrap: 'wrap', gap: 1}}>
                  {recommendation.safety.map((tip, index) => (
                    <Chip
                      key={index}
                      label={tip}
                      color="error"
                      variant="outlined"
                    />
                  ))}
                </Box>
              </CardContent>
            </Card>
          )}
        </>
      )}
    </Box>
  )
}

export default ActivityDetail
